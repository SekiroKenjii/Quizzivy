// Command gencontract writes the API contract as the server serves it for
// download: api/openapi.yaml converted to JSON, and the package that embeds it.
// It is run by make gen, so the output is committed and CI fails on drift.
package main

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"

	"quizzivy/internal/platform/apidocs"
)

const packageSource = `// Code generated by cmd/gencontract from api/openapi.yaml. DO NOT EDIT.

// Package contract holds the API contract as it is written in api/openapi.yaml,
// converted to JSON in the same order, for the download the Admin console offers.
package contract

import _ "embed"

//go:embed openapi.json
var document []byte

// JSON returns the contract document. The caller must not modify it.
func JSON() []byte { return document }
`

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string) error {
	if len(args) != 2 {
		return errors.New("usage: gencontract <openapi.yaml> <output directory>")
	}
	source, err := os.ReadFile(args[0])
	if err != nil {
		return err
	}
	document, err := apidocs.ContractJSON(source)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(args[1], 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(args[1], "openapi.json"), document, 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(args[1], "contract.gen.go"), []byte(packageSource), 0o644)
}
