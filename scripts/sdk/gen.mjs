#!/usr/bin/env node
// Writes the generated half of the @quizzivy/sdk package (D-080) from the
// contract: the YAML and JSON documents, the operation map and the version.
// `make gen` runs it after cmd/gencontract and before openapi-typescript.
//   gen.mjs <openapi.yaml> <openapi.json> <sdk directory>
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'];

const HEADER = '// Code generated by scripts/sdk/gen.mjs from api/openapi.yaml. DO NOT EDIT.\n';

/**
 * operationsOf lists every operation in a contract document by operationId,
 * in document order. A missing or repeated operationId is an error: a client
 * calls operations by that name, so it must name exactly one.
 */
export function operationsOf(document) {
  const operations = [];
  const seen = new Set();
  for (const [path, item] of Object.entries(document.paths ?? {})) {
    for (const method of METHODS) {
      const operation = item[method];
      if (operation === undefined) continue;
      const id = operation.operationId;
      if (typeof id !== 'string' || id === '') throw new Error(`${method.toUpperCase()} ${path} has no operationId`);
      if (seen.has(id)) throw new Error(`operationId ${id} is used twice`);
      seen.add(id);
      operations.push({ id, method, path });
    }
  }
  return operations;
}

/** versionOf returns info.version, which must be a plain semver (D-080). */
export function versionOf(document) {
  const version = document.info?.version;
  if (typeof version !== 'string' || !/^\d+\.\d+\.\d+$/.test(version)) {
    throw new Error(`info.version must be MAJOR.MINOR.PATCH, got ${JSON.stringify(version)}`);
  }
  return version;
}

/** renderModule returns operations.js and operations.d.ts for a contract. */
export function renderModule(document) {
  const version = versionOf(document);
  const operations = operationsOf(document);
  const js = [
    HEADER,
    `export const CONTRACT_VERSION = ${JSON.stringify(version)};`,
    '',
    'export const OPERATIONS = Object.freeze({',
    ...operations.map(
      ({ id, method, path }) =>
        `  ${JSON.stringify(id)}: Object.freeze({ method: ${JSON.stringify(method)}, path: ${JSON.stringify(path)} }),`,
    ),
    '});',
    '',
  ].join('\n');
  const dts = [
    HEADER,
    '/** The contract version this package was generated from: info.version, the app release (D-080). */',
    `export declare const CONTRACT_VERSION: ${JSON.stringify(version)};`,
    '',
    '/** Every operation in the contract by operationId, with its method and path template. */',
    'export declare const OPERATIONS: {',
    ...operations.map(
      ({ id, method, path }) =>
        `  readonly ${JSON.stringify(id)}: { readonly method: ${JSON.stringify(method)}; readonly path: ${JSON.stringify(path)} };`,
    ),
    '};',
    '',
    'export type OperationId = keyof typeof OPERATIONS;',
    '',
  ].join('\n');
  return { js, dts };
}

/** withVersion returns package.json text with its version set, the rest as it was. */
export function withVersion(manifestText, version) {
  const manifest = JSON.parse(manifestText);
  manifest.version = version;
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

function main([yamlPath, jsonPath, sdkDir]) {
  if (!sdkDir) {
    console.error('usage: gen.mjs <openapi.yaml> <openapi.json> <sdk directory>');
    process.exit(2);
  }
  const document = JSON.parse(readFileSync(jsonPath, 'utf8'));
  const { js, dts } = renderModule(document);
  copyFileSync(yamlPath, join(sdkDir, 'openapi.yaml'));
  copyFileSync(jsonPath, join(sdkDir, 'openapi.json'));
  writeFileSync(join(sdkDir, 'operations.js'), js);
  writeFileSync(join(sdkDir, 'operations.d.ts'), dts);
  const manifestPath = join(sdkDir, 'package.json');
  writeFileSync(manifestPath, withVersion(readFileSync(manifestPath, 'utf8'), versionOf(document)));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
